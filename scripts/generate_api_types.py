"""Generate TypeScript DTOs from this project's exported OpenAPI, without npm tooling.

This is intentionally a limited converter: unsupported schema constructs fail.
JSON Schema constraints still belong to the API's runtime Pydantic validation.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def ts_type(schema: dict) -> str:
    if not isinstance(schema, dict):
        raise ValueError("Expected a schema mapping")
    unsupported = {"not", "if", "then", "else", "patternProperties", "prefixItems", "dependentSchemas"} & schema.keys()
    if unsupported:
        raise ValueError(f"Unsupported schema constructs: {sorted(unsupported)}")
    if "$ref" in schema:
        prefix = "#/components/schemas/"
        if not schema["$ref"].startswith(prefix):
            raise ValueError("Only local component schema references are supported")
        name = schema["$ref"][len(prefix):].replace("~1", "/").replace("~0", "~")
        return f'components["schemas"][{json.dumps(name)}]'
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"]) or "never"
    for key, operator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return "(" + operator.join(ts_type(item) for item in schema[key]) + ")"
    kind = schema.get("type")
    if isinstance(kind, list):
        return "(" + " | ".join(ts_type({**schema, "type": item}) for item in kind) + ")"
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"integer", "number"}:
        return "number"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema or "additionalProperties" in schema:
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        members = [f'{json.dumps(name, ensure_ascii=False)}{"" if name in required else "?"}: {ts_type(value)};'
                   for name, value in properties.items()]
        extra = schema.get("additionalProperties", True)
        if extra is True:
            members.append("[key: string]: unknown;")
        result = "{ " + " ".join(members) + " }"
        if isinstance(extra, dict):
            mapping = f"Record<string, {ts_type(extra)}>"
            result = f"({result} & {mapping})" if members else mapping
        return result
    if kind is None and not (schema.keys() - {"title", "description", "default", "examples", "example", "deprecated", "readOnly", "writeOnly"}):
        return "unknown"  # The actual schema is explicitly unconstrained.
    raise ValueError(f"Unsupported schema type: {kind!r}")


def generate(source: Path, destination: Path) -> None:
    document = json.loads(source.read_text("utf-8"))
    schemas = document["components"]["schemas"]
    lines = ["// Generated by scripts/generate_api_types.py from docs/openapi.json. Do not edit.",
             "export interface components {", "  schemas: {"]
    for name, schema in sorted(schemas.items()):
        lines.append(f"    {json.dumps(name)}: {ts_type(schema)};")
    lines.extend(["  };", "}", ""])
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=ROOT / "docs/openapi.json")
    parser.add_argument("--output", type=Path, default=ROOT / "frontend/src/api/generated.ts")
    args = parser.parse_args()
    generate(args.input, args.output)
    print(args.output)


if __name__ == "__main__":
    main()
